"""The BUILD_SPEC 6 robustness matrix.

The brief asks that one malformed file not fail the batch. The standard built to
is stronger: **nothing crashes, ever**. Every case below must either produce
schema-valid output or a clean `status="failed"` with a reason -- never an
unhandled exception, and never a partially-populated result.

These run on the DSP-only stack by default so they are fast and need no model
downloads; the isolation being tested lives in `pipeline.py`, above the models.
"""
from __future__ import annotations

import json

import pytest

from voicetone import FileResult, analyze_file
from voicetone.schema import FIELDS, CallAnalysis
from voicetone.stack import build_predictors

STACK = "vad,quality,noise"


def _run(path) -> FileResult:
    return analyze_file(path, list(build_predictors(STACK)))


def _assert_wellformed(r: FileResult) -> None:
    """Either a clean failure with a reason, or output that validates."""
    assert r.status in ("ok", "failed")
    if r.status == "failed":
        assert r.error, "a failed file must say why"
        assert r.result is None
        return
    assert r.result is not None
    assert set(r.result) == set(FIELDS), "output must carry exactly the schema"
    CallAnalysis(**r.result)                       # revalidates every rule
    json.dumps(r.result)                           # must be serialisable
    assert 0.0 <= r.result["confidence"] <= 1.0


# --------------------------------------------------------------------------
# structurally invalid input -> clean failure
# --------------------------------------------------------------------------

def test_zero_byte_file(broken):
    r = _run(broken["zero_byte"])
    assert r.status == "failed"
    assert "zero" in r.error.lower() or "ffprobe" in r.error.lower()
    _assert_wellformed(r)


def test_text_file_with_audio_extension(broken):
    r = _run(broken["text_as_wav"])
    assert r.status == "failed"
    _assert_wellformed(r)


def test_truncated_file(broken):
    if "truncated" not in broken:
        pytest.skip("samples not present")
    _assert_wellformed(_run(broken["truncated"]))    # may decode or fail; not crash


def test_missing_file():
    r = _run("/nonexistent/nope.wav")
    assert r.status == "failed"
    _assert_wellformed(r)


def test_unsupported_extension(tmp_path):
    p = tmp_path / "notes.txt"
    p.write_text("hello")
    r = _run(p)
    assert r.status == "failed"
    assert "unsupported" in r.error.lower()


# --------------------------------------------------------------------------
# valid audio, awkward content -> valid output
# --------------------------------------------------------------------------

@pytest.mark.parametrize("key", [
    "pure_silence", "white_noise", "clip_half_second", "square_wave",
    "dtmf", "hold_music",
])
def test_awkward_content_produces_valid_output(broken, key):
    r = _run(broken[key])
    assert r.status == "ok", f"{key} should decode: {r.error}"
    _assert_wellformed(r)


def test_pure_silence_reports_long_silence(broken):
    r = _run(broken["pure_silence"])
    assert r.result["long_silence_present"] is True
    assert r.result["confidence"] < 0.75, "no evidence should mean low confidence"


def test_white_noise_has_no_speech_and_low_confidence(broken):
    r = _run(broken["white_noise"])
    assert r.latents["speech_ratio"] == 0.0
    assert r.result["confidence"] < 0.8


def test_square_wave_is_impaired(broken):
    """A fully-clipped signal must not come back `clear`."""
    r = _run(broken["square_wave"])
    assert r.result["audio_quality"] in ("slightly_impaired", "severely_impaired")


def test_half_second_clip_does_not_crash(broken):
    _assert_wellformed(_run(broken["clip_half_second"]))


