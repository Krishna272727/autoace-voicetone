@pytest.mark.parametrize("key", ["mulaw_8k", "surround_5_1", "true_stereo",
                                 "video_container", "unicode_name"])
def test_format_variations(broken, key):
    if key not in broken:
        pytest.skip(f"{key} could not be generated by this ffmpeg build")
    r = _run(broken[key])
    assert r.status == "ok", f"{key} should decode: {r.error}"
    _assert_wellformed(r)


def test_8k_mulaw_is_band_limited(broken):
    if "mulaw_8k" not in broken:
        pytest.skip("no mulaw fixture")
    r = _run(broken["mulaw_8k"])
    # Telephony band-limiting is a real if mild impairment (BUILD_SPEC 6).
    assert r.result["audio_quality"] in ("clear", "slightly_impaired")
    assert r.latents["quality_detail"]["native_sr"] == 8000.0


def test_true_stereo_is_detected_as_dual_channel(broken):
    if "true_stereo" not in broken:
        pytest.skip("no stereo fixture")
    from voicetone import load
    ctx = load(broken["true_stereo"])
    assert ctx.true_stereo, "genuinely different channels must not be downmixed blindly"


def test_fake_stereo_is_detected(samples):
    """The provided calls are a mono downmix in a stereo container."""
    if not samples:
        pytest.skip("samples not present")
    from voicetone import load
    ctx = load(samples[0])
    assert ctx.n_channels == 2
    assert not ctx.true_stereo
    assert ctx.channel_corr > 0.98


def test_unicode_filename_is_preserved_exactly(broken):
    if "unicode_name" not in broken:
        pytest.skip("no unicode fixture")
    src = broken["unicode_name"]
    r = _run(src)
    assert r.name == src.name, "the original filename must survive verbatim"
    assert "✅" in r.name and "📞" in r.name


# --------------------------------------------------------------------------
# batch-level isolation
# --------------------------------------------------------------------------

def test_one_bad_file_does_not_kill_the_batch(broken, samples):
    from voicetone import analyze_batch
    if not samples:
        pytest.skip("samples not present")
    paths = [broken["zero_byte"], samples[0], broken["text_as_wav"]]
    results = analyze_batch(paths, list(build_predictors(STACK)))
    assert len(results) == 3
    assert results[1].status == "ok"
    assert sum(r.status == "failed" for r in results) == 2
    for r in results:
        _assert_wellformed(r)


def test_a_failing_predictor_is_skipped_not_fatal(samples):
    """Predictor-level isolation: one broken stage must not lose the file."""
    if not samples:
        pytest.skip("samples not present")

    class Exploding:
        name = "exploding"

        def __call__(self, ctx, lat):
            raise RuntimeError("boom")

    r = analyze_file(samples[0], [Exploding(), *build_predictors(STACK)])
    assert r.status == "ok"
    assert any("exploding" in w for w in r.warnings)
    _assert_wellformed(r)
